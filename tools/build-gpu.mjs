#!/usr/bin/env node
// tools/build-gpu.mjs — bundles lib/gpu/index.js into the lazy chunk
// dist/explainers-gpu.v1.js (ESM, minified, es2020; no dependencies) with
// esbuild from tools/node_modules, and refreshes dist/integrity.json. The
// chunk is a dynamic import() of the runtime (lib/site/gpu.js) on the first
// approach of a splat3d figure, so no <script> carries its hash; the manifest
// entry exists for the deploy check and the tests. Sibling of build-3d.mjs.
// Run: node tools/build-gpu.mjs [--check]   (--check exits 1 when stale)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { writeIntegrity, INTEGRITY_FILE } from './integrity.mjs';
import { gzipSize, stripTrailingWhitespace } from './build-3d.mjs';

export const GPU_CHUNK_VERSION = '1.0.0';
export const GPU_OUTFILE = 'dist/explainers-gpu.v1.js';
export const GPU_ENTRY = 'lib/gpu/index.js';
export const GPU_GZIP_BUDGET = 20 * 1000;

const toolsDir = path.dirname(fileURLToPath(import.meta.url));
export const root = path.resolve(toolsDir, '..');
const require = createRequire(path.join(toolsDir, 'package.json'));

// Returns { code } without touching dist/.
export async function buildGpuChunk({ minify = true } = {}) {
  const { build } = await import(require.resolve('esbuild'));
  const banner = [
    `// explainers-gpu v${GPU_CHUNK_VERSION} — GENERATED by tools/build-gpu.mjs from lib/gpu/ (+ lib/scene3d/mesh.js); do not edit.`,
    '// Lazy ESM chunk: imported by dist/explainers-runtime.v1.js on the first approach of a splat3d figure. Contract: DESIGN.md Decision 39.',
  ].join('\n');
  const result = await build({
    entryPoints: [path.join(root, GPU_ENTRY)],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    minify,
    treeShaking: true,
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: banner },
  });
  return { code: stripTrailingWhitespace(result.outputFiles[0].text) };
}

const invoked = process.argv[1] && /build-gpu\.mjs$/.test(process.argv[1]);
if (invoked) {
  const { code } = await buildGpuChunk();
  const file = path.join(root, GPU_OUTFILE);
  const gz = gzipSize(code);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (current !== code) { console.error(`${GPU_OUTFILE} is stale; run: node tools/build-gpu.mjs`); process.exit(1); }
    if (writeIntegrity(root, { check: true }).changed) { console.error(`${INTEGRITY_FILE} is stale; run: node tools/build-gpu.mjs`); process.exit(1); }
    console.log(`${GPU_OUTFILE} current (${code.length} bytes, ${gz} gzip)`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, code);
    console.log(`wrote ${GPU_OUTFILE}: ${code.length} bytes, ${gz} gzip (budget ${GPU_GZIP_BUDGET} gzip)`);
    if (gz > GPU_GZIP_BUDGET) { console.error(`${GPU_OUTFILE} exceeds the ${GPU_GZIP_BUDGET} byte gzip budget`); process.exit(1); }
    const { changed } = writeIntegrity(root);
    console.log(changed ? `wrote ${INTEGRITY_FILE}; run: node tools/explainers.cjs build articles/*/index.html` : `${INTEGRITY_FILE} current`);
  }
}
